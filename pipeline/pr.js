// Creates a branch + commit and opens a PR with `gh` (if available).
// Videos are copied into out/pr/<ticket>/ so they can be attached/linked.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { git } from './repo.js';

export function openPr({ root, ticketId, bug, verdict, diff, beforeVideo, afterVideo, specRel, log, dryRun }) {
  const outDir = path.join(root, 'out', 'pr', ticketId);
  fs.mkdirSync(outDir, { recursive: true });
  if (beforeVideo) fs.copyFileSync(beforeVideo, path.join(outDir, 'before.webm'));
  if (afterVideo) fs.copyFileSync(afterVideo, path.join(outDir, 'after.webm'));

  const body = `${verdict.pr_description}

---
**Ticket:** \`${ticketId}\`
**Reproduction test:** \`${specRel}\`
**Verifier verdict:** \`${verdict.verdict}\`

<details><summary>What the verifier saw</summary>

**Customer recording:** ${verdict.original_video_summary}

**Fixed build:** ${verdict.fixed_video_summary}

**Comparison:** ${verdict.comparison}
</details>

Before / after recordings: \`out/pr/${ticketId}/before.webm\`, \`out/pr/${ticketId}/after.webm\`

🤖 Generated by TicketFix with Gemini 4 Argon.
`;
  fs.writeFileSync(path.join(outDir, 'PR.md'), `# ${bug.title}\n\n${body}`);
  fs.writeFileSync(path.join(outDir, 'fix.diff'), diff);
  log(`📦 PR package written to out/pr/${ticketId}/`);

  if (dryRun) return { url: null, outDir };

  const branch = `ticketfix/${ticketId}`;
  try {
    git(root, `checkout -b ${branch}`);
    git(root, 'add app');
    git(root, `commit -m "fix: ${bug.title.replace(/"/g, '\\"')}" -m "Ticket ${ticketId}. Auto-generated by TicketFix."`);
    log(`   committed on ${branch}`);
  } catch (e) {
    log(`   ! git commit failed: ${e.message.split('\n')[0]}`);
    return { url: null, outDir };
  }

  const gh = spawnSync('gh', ['pr', 'create', '--title', bug.title, '--body-file', path.join(outDir, 'PR.md'), '--head', branch], { cwd: root, encoding: 'utf8' });
  if (gh.status === 0) {
    const url = gh.stdout.trim().split('\n').pop();
    log(`🚀 PR opened: ${url}`);
    return { url, outDir };
  }
  log(`   ! gh pr create failed (is gh installed/authed and the branch pushed?): ${(gh.stderr || '').trim().split('\n')[0]}`);
  return { url: null, outDir };
}
